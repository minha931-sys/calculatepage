  function esc(text){
    return String(text || '').replace(/[&<>"']/g, ch => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[ch]));
  }

  function collectFields(){
    const labels = [...root.querySelectorAll('.calculator-box label span, .calculator-box th, .calculator-box summary')]
      .map(el => el.textContent.replace(/\s+/g,' ').trim())
      .filter(Boolean)
      .filter(text => !/열기|접기|자세히|고급/.test(text));
    const unique = [];
    labels.forEach(text => {
      if(text.length > 1 && !unique.includes(text)) unique.push(text);
    });
    return unique.slice(0, 8);
  }

